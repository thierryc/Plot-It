// Run with playwright-cli run-code --filename against an isolated Vite origin.
async (page) => {
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.evaluate(() => { localStorage.removeItem('plot-it-document'); localStorage.setItem('plot-it-theme', 'light'); });
  await page.reload();
  await page.getByRole('button', { name: 'Main menu', exact: true }).waitFor();
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await settle();
  const box = selector => page.locator(selector).boundingBox();
  let stage = await box('#stage'), paper = await box('#paper'), toolbar = await box('[data-ui="drawing-toolbar"]');
  assert(stage && paper && toolbar && paper.y >= toolbar.y + toolbar.height && paper.y + paper.height < stage.y + stage.height - 60, 'Fit overlaps floating controls');
  assert(await page.locator('[data-inspector-dock] [data-ui="inspector"]').isVisible(), 'Desktop inspector is hidden');
  await page.screenshot({ path: 'output/playwright/layout-desktop-light.png' });
  await page.getByRole('button', { name: 'Main menu', exact: true }).click();
  await page.getByRole('button', { name: 'Rename plot', exact: true }).click();
  await page.getByRole('textbox', { name: 'Plot name', exact: true }).fill('Layout review');
  await page.getByRole('textbox', { name: 'Plot name', exact: true }).press('Enter');
  assert((await page.locator('[data-document-name]').textContent()) === 'Layout review', 'Rename failed');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert(await page.locator('[data-document-name]').textContent() === 'Untitled plot', 'Rename undo failed');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.getByRole('button', { name: 'Shapes', exact: true }).click();
  await page.getByRole('button', { name: 'Rectangle', exact: true }).click();
  assert(await page.locator('#artwork-layer [data-item-id]').count() === 1, 'Shape insertion failed');
  assert(await page.getByRole('heading', { name: 'Plot-It', exact: true }).count() === 0, 'Empty state remains after insertion');
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert(await page.locator('#artwork-layer [data-item-id]').count() === 0, 'Shape undo failed');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.getByRole('button', { name: 'Main menu', exact: true }).click();
  await page.getByRole('combobox', { name: 'Interface theme', exact: true }).selectOption('dark');
  assert(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()) === '#0B99FF', 'Wrong dark accent');
  await settle();
  const anchoredMenu = await box('#main-menu');
  assert(anchoredMenu.x === 16 && anchoredMenu.y >= 56, 'Main menu is not anchored below its trigger');
  await page.screenshot({ path: 'output/playwright/layout-desktop-dark-menu.png' });
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button', { name: 'Main menu', exact: true }).evaluate(node => node === document.activeElement), 'Menu did not restore focus');
  await page.screenshot({ path: 'output/playwright/layout-desktop-dark.png' });
  await page.getByRole('radio', { name: 'Plot', exact: true }).click();
  await page.locator('[data-plot-destination]').waitFor();
  assert(await page.locator('[data-ui="drawing-toolbar"]').evaluate(node => node.inert), 'Plot mode did not lock drawing tools');
  assert(await page.getByRole('button', { name: 'Undo', exact: true }).evaluate(node => node.inert), 'Plot mode did not lock undo');
  assert(!await page.getByRole('button', { name: 'Zoom in', exact: true }).evaluate(node => node.closest('[inert]') !== null), 'Plot mode locked zoom');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  assert(await page.locator('[data-zoom-label]').textContent() === '110%', 'Plot zoom failed');
  await page.getByRole('button', { name: 'Fit to view', exact: true }).click();
  await page.screenshot({ path: 'output/playwright/layout-plot-dark.png' });
  await page.getByRole('radio', { name: 'Edit', exact: true }).click();
  assert(!await page.locator('[data-ui="drawing-toolbar"]').evaluate(node => node.inert), 'Edit controls stayed locked');
  await page.getByRole('button', { name: 'Main menu', exact: true }).click();
  const saved = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  assert((await saved).suggestedFilename() === 'Layout review.plit.json', 'Save filename changed');
  await page.getByRole('button', { name: 'Main menu', exact: true }).click();
  const exported = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export SVG', exact: true }).click();
  assert((await exported).suggestedFilename().endsWith('.svg'), 'Export failed');
  const documentFile = await page.evaluate(async () => {
    const { serializePlotIt } = await import('/src/document-file.ts');
    return serializePlotIt(JSON.parse(localStorage.getItem('plot-it-document')));
  });
  await page.locator('#document-input').setInputFiles({ name: 'restored.plit.json', mimeType: 'application/json', buffer: Buffer.from(documentFile) });
  await page.waitForFunction(() => document.querySelector('[data-document-name]')?.textContent === 'Layout review');
  await page.locator('#file-input').setInputFiles({ name: 'sample.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20"><circle cx="10" cy="10" r="8" fill="none" stroke="#123456"/></svg>') });
  await page.waitForFunction(() => document.querySelectorAll('#artwork-layer [data-item-id]').length === 2);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  assert(await page.locator('#artwork-layer [data-item-id]').count() === 1, 'Import undo failed');
  await page.getByRole('button', { name: 'More elements', exact: true }).click();
  await settle();
  const extra = await box('#more-elements'), extraTrigger = await box('[data-action="more-elements"]');
  assert(extra && extraTrigger && extra.y >= extraTrigger.y + extraTrigger.height, 'More Elements menu not below toolbar');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Change canvas size', exact: true }).click();
  assert(await page.locator('#canvas-dialog').evaluate(node => node.matches(':modal')), 'Canvas size dialog not modal');
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button', { name: 'Change canvas size', exact: true }).evaluate(node => node === document.activeElement), 'Canvas dialog did not restore focus');
  for (const width of [768, 640]) {
    await page.setViewportSize({ width, height: 900 });
    await settle();
    assert(await page.locator('[data-inspector-dock] [data-ui="inspector"]').isVisible(), `Inspector hidden at ${width}`);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow at ${width}`);
    await page.screenshot({ path: `output/playwright/layout-tablet-${width}.png` });
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await settle();
  assert(!await page.locator('[data-inspector-dock]').isVisible(), 'Phone inspector still docked');
  await page.screenshot({ path: 'output/playwright/layout-phone-dark.png' });
  await page.getByRole('button', { name: 'Inspector', exact: true }).click();
  assert(await page.locator('#inspector-drawer').evaluate(node => node.matches(':modal')), 'Inspector is not modal');
  assert(await page.locator('#inspector-drawer [data-ui="inspector"]').count() === 1, 'Inspector duplicated');
  await page.screenshot({ path: 'output/playwright/layout-phone-drawer.png' });
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button', { name: 'Inspector', exact: true }).evaluate(node => node === document.activeElement), 'Drawer did not restore focus');
  await page.getByRole('radio', { name: 'Plot', exact: true }).click();
  assert(await page.locator('#inspector-drawer').evaluate(node => node.matches(':modal')), 'Phone Plot controls unavailable');
  await page.setViewportSize({ width: 800, height: 900 });
  await page.locator('[data-inspector-dock] [data-plot-sidebar]').waitFor();
  assert(!await page.locator('#inspector-drawer').evaluate(node => node.open), 'Drawer stayed modal on desktop');
  await page.getByRole('radio', { name: 'Edit', exact: true }).click();
  await page.setViewportSize({ width: 320, height: 700 });
  await page.getByRole('button', { name: 'Main menu', exact: true }).click();
  await settle();
  const menu = await box('#main-menu');
  assert(menu && menu.x >= 0 && menu.x + menu.width <= 320 && menu.y >= 0 && menu.y + menu.height <= 700, 'Phone menu clipped');
  await page.getByRole('combobox', { name: 'Interface theme', exact: true }).selectOption('light');
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'output/playwright/layout-small-phone-light.png' });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone overflows');
  assert(!errors.length, `Browser errors: ${errors.join('; ')}`);
  return { passed: true, screenshots: 10, themes: ['light', 'dark'], widths: [1440, 800, 768, 640, 390, 320] };
}
